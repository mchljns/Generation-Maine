<h2 class="wp-block-heading">A storytelling project made by young Mainers</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Generation Maine is a group of 8 to 12 young content creators from across the state. Each one makes short videos about their own life in Maine.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The videos show how economic rules affect everyday choices. Some are about finding a place to live. Others are about getting a job, starting a business or deciding whether to stay.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
