def post_editor_rules(css):
    """The post and page editor shows the title and the content without the template: the page's rules for the title and the
    content again, for the editor's title field and content root. Rules inside @media blocks are not copied."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules = re.findall(r"[^{}]*(?:\.gm-title|\.gm-entry|main\.gm-page )[^{}]*\{[^{}]*\}", css)
    root = ".is-root-container.wp-block-post-content"
    return "".join(r.strip().replace("main.gm-page ", root + " ").replace(".gm-entry", root).replace(".gm-title", ".editor-post-title") + "\n" for r in rules)


