def images():
    out = os.path.join(THEME, "assets", "img")
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        os.remove(os.path.join(out, f))
    # the page swaps the old marigold for Maine Policy's gold at build time; the brand files still carry the old value
    for src, dst in (("lockup-compact-reversed.svg", "lockup-compact-reversed.svg"), ("lockup-two-line-reversed.svg", "lockup-two-line-reversed.svg"), ("favicon.svg", "icon.svg")):
        svg = open(os.path.join(F.LOGO_A, src), encoding="utf-8").read()
        open(os.path.join(out, dst), "w", encoding="utf-8").write(re.sub("#EFB443", L.MG, svg, flags=re.I))
    shutil.copy(os.path.join(PAGE, "media", "share.jpg"), os.path.join(out, "share-card.jpg"))
    shutil.copy(os.path.join(PAGE, "media", "about.jpg"), os.path.join(out, "about.jpg"))
    # the thumbnail WordPress shows under Appearance > Themes
    subprocess.run(["node", os.path.join(ROOT, "brand", "src", "theme_shot.mjs"), os.path.join(PAGE, "index.html"), os.path.join(THEME, "screenshot.png")], check=True)
    from PIL import Image
    gold_icon = os.path.join(out, "_app-icon.svg")
    open(gold_icon, "w", encoding="utf-8").write(re.sub("#EFB443", L.MG, open(os.path.join(F.LOGO_A, "app-icon.svg"), encoding="utf-8").read(), flags=re.I))
    for size in (180, 192):
        tmp = os.path.join(out, "icon.html")
        open(tmp, "w").write('<!doctype html><meta charset="utf-8"><style>body{margin:0;width:%dpx;height:%dpx}img{width:%dpx;height:%dpx;display:block}</style><img src="file://%s">'
                             % (size, size, size, size, gold_icon))
        png = os.path.join(out, "icon-%d.png" % size)
        shot(tmp, png, size)
        os.remove(tmp)
        Image.open(png).convert("RGB").crop((0, 0, size, size)).save(png)
    os.remove(gold_icon)
    Image.open(os.path.join(out, "icon-192.png")).save(os.path.join(out, "favicon.ico"), sizes=[(16, 16), (32, 32), (48, 48)])


def fonts():
    """DM Sans and Michroma as WOFF2, converted from their TTF files as the v2 page converts them (Bricolage ships as WOFF2
    already). dm-sans-var.ttf stays beside them as the brand builders' copy of DM Sans; package_theme.py leaves it out of the zip."""
    d = os.path.join(THEME, "assets", "fonts")
    for src, name in (("generation-maine/assets/fonts/dm-sans-var.ttf", "dm-sans-var.woff2"), ("brand/fonts/michroma/Michroma-Regular.ttf", "michroma-regular.woff2")):
        with open(os.path.join(d, name), "wb") as fh:
            fh.write(L.woff2(src))
    if os.path.exists(os.path.join(d, "michroma-regular.ttf")):
        os.remove(os.path.join(d, "michroma-regular.ttf"))
    shutil.copy(os.path.join(ROOT, "brand", "fonts", "michroma", "OFL.txt"), os.path.join(d, "OFL-Michroma.txt"))


def build():
    html = page_html()
    css = page_css(html)
    wp = WP_ADDITIONS.replace("$OUT", OUT)
    style = HEADER % {"version": VERSION} + FONT_FACES % {"dir": "assets/fonts/"} + drop_empty(map_selectors(css, wp_selector)) + wp
    editor = ("/* Editor canvas styles for Generation Maine. Generated by brand/src/build_theme.py. */\n" + FONT_FACES % {"dir": "../fonts/"}
              + drop_empty(map_selectors(css, editor_selector)) + wp
              + EDITOR_ADDITIONS % {"bars": bars_uri("#FFFFFF"), "bars_blue": bars_uri(L.LEAN_A["blue"])} + post_editor_rules(wp))
    js = site_js(html)
    foot = footer_template(html)
    write("generation-maine/style.css", style)
    write("generation-maine/assets/css/editor.css", editor)
    write("generation-maine/assets/js/site.js", js)
    write("generation-maine/assets/data/footer.html", foot)
    write("generation-maine/assets/data/mural.json", re.sub("#EFB443", L.MG, json.dumps(F.MURAL_A, separators=(",", ":")), flags=re.I))
    write("generation-maine/inc/marks.php", marks_php())
    write("generation-maine/theme.json", theme_json())
    fonts()
    images()
    digest = hashlib.sha1((style + js + foot).encode()).hexdigest()[:7]
    stamp = digest + " " + datetime.datetime.utcnow().strftime("%b %d %H:%M UTC")
    write("generation-maine/inc/build.php", "<?php\n/**\n * Build stamp. Generated by brand/src/build_theme.py.\n *\n * @package generation-maine\n */\n\n"
          "define( 'GM_THEME_VERSION', '%s' );\ndefine( 'GM_BUILD_HASH', '%s' );\ndefine( 'GM_BUILD', '%s' );\n" % (VERSION, digest, stamp))
    print("theme %s: style.css %d bytes, editor.css, site.js %d bytes, footer.html, mural.json, marks.php, theme.json, fonts, images" % (stamp, len(style), len(js)))


if __name__ == "__main__":
    build()
