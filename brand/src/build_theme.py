def footer_template(html):
    """The family footer exactly as the page renders it, with tokens for what the theme fills from its settings."""
    f = re.search(r'<footer class="site">(.*?)</footer>', html, re.S).group(1)
    f = re.sub(r"<script>document\.querySelectorAll\(\"\.yr\"\).*?</script>", "", f, flags=re.S)
    def rep(pattern, token):
        nonlocal f
        new, n = re.subn(pattern, token, f, count=1, flags=re.S)
        assert n == 1, pattern
        f = new
    rep(r'<p class="lede">.*?</p>', '<p class="lede">{{LINE}}</p>')
    rep(r'&copy; <span class="yr">\d{4}</span> .*?</p>', '&copy; {{YEAR}} {{LEGAL}}</p>')
    rep(r'<span class="ph build"[^>]*>.*?</span>', "{{BUILD}}")
    rep(r'<span class="ph" title="\[CONFIRM: privacy policy page\]">Privacy</span>', "{{PRIVACY}}")
    rep(r'<a href="https://mainepolicy\.org/contact/[^"]*"[^>]*>Contact</a>', "{{CONTACT}}")
    return f.strip() + "\n"


