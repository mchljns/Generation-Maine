def split_rule_prelude(prelude):
    """A rule's prelude may carry the comments that sat above it. Return (comments, selector list)."""
    m = re.match(r"(\s*(?:/\*.*?\*/\s*)*)(.*)", prelude, re.S)
    return m.group(1), m.group(2)


def map_selectors(css, fn):
    """Apply fn(selector) -> list of selectors to every selector in every rule; @-rules and keyframe steps pass through."""
    def sub(m):
        lead, sel = split_rule_prelude(m.group(1))
        t = sel.strip()
        if not t or t.startswith("@") or re.match(r"^(from|to|[\d.]+%)(\s*,\s*(from|to|[\d.]+%))*$", t):
            return m.group(0)
        out = []
        for one in t.split(","):
            out.extend(fn(one.strip()))
        if not out:
            return lead + "._gm-dropped{"
        return lead + ",".join(out) + "{"
    return re.sub(r"([^{}]*)\{", sub, css)


def wp_selector(sel):
    """The page's buttons are links with .btn; WordPress renders core buttons. Alias the one to the other."""
    if ".top .cta" in sel:
        return [sel.replace(".top .cta", ".top .cta>.wp-block-button__link")]
    if re.search(r"\.btn(?![\w-])", sel):
        alias = sel.replace(".btn.b1", ".wp-block-button.b1>.wp-block-button__link").replace(".btn.b2", ".wp-block-button.b2>.wp-block-button__link")
        alias = re.sub(r"\.btn(?![\w-])", ".wp-block-button>.wp-block-button__link", alias)
        return [sel, alias]
    return [sel]


def editor_selector(sel):
    """In the editor canvas there is no <html> class list and no JS: drop JS-only states, unwrap the root qualifiers."""
    if re.match(r"^(\.static)?\.js\b", sel) or sel.startswith("html.vopen") or ".vopen" in sel:
        return []
    sel = re.sub(r"^(\.static\.lean|\.euro\.lean|\.static|\.lean|\.euro)\s+", "", sel)
    out = wp_selector(sel)
    # the bar and the footer are template parts; edited on their own there is no header.top or footer.site around them,
    # so their own wrappers (.gm-bar, .gm-foot) carry the same rules
    extra = []
    for x in out:
        if re.match(r"^\.top(?=$|[\s.:>\[])", x):
            extra.append(".gm-bar" + x[4:])
        if re.match(r"^\.site(?=$|[\s.:>\[])", x):
            extra.append(".gm-foot" + x[5:])
    return out + extra


def page_css(html):
    css = re.search(r"<style>(.*?)</style>", html, re.S).group(1)
    css = re.sub(r"@font-face\{[^}]*\}\s*", "", css)
    css = css.replace("calc(9 * 80vh", "calc(var(--n,9) * 80vh").replace("calc(9 * 520px)", "calc(var(--n,9) * 520px)")
    assert "base64" not in css, "a font is still inlined"
    return css.strip() + "\n"


def drop_empty(css):
    return re.sub(r"\._gm-dropped\{[^}]*\}", "", css)


def bars_uri(color):
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 30 12"><path d="M4 12 L8 0 h5 L9 12z" fill="%s"/>'
           '<path d="M12 12 L16 0 h5 L17 12z" fill="%s"/><path d="M20 12 L24 0 h5 L25 12z" fill="#FAC800"/></svg>' % (color, color))
    return "url(\"data:image/svg+xml,%s\")" % svg.replace("#", "%23").replace('"', "'").replace("<", "%3C").replace(">", "%3E")


